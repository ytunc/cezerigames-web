// Global Language Controller
function getSavedLanguage() {
  // 1. Explicit URL parameter: ?lang=EN
  const urlParams = new URLSearchParams(window.location.search);
  const langParam = urlParams.get('lang');
  if (langParam && I18N_DATA[langParam.toUpperCase()]) {
    return langParam.toUpperCase();
  }

  // 2. Previously chosen language in localStorage
  const saved = localStorage.getItem('cezeri_lang');
  if (saved && I18N_DATA[saved]) return saved;
  
  // 3. Automatic Device / Browser Language Detection (navigator.languages)
  const candidateLangs = navigator.languages && navigator.languages.length 
    ? navigator.languages 
    : [navigator.language || navigator.userLanguage || ''];

  for (const raw of candidateLangs) {
    if (!raw) continue;
    const code = raw.slice(0, 2).toLowerCase();
    if (code === 'tr') return 'TR';
    if (code === 'de') return 'DE';
    if (code === 'fr') return 'FR';
    if (code === 'es') return 'ES';
    if (code === 'pt') return 'PR';
    if (code === 'en') return 'EN';
  }

  // Default fallback for international visitors
  return 'EN';
}

function setLanguage(langCode) {
  if (!I18N_DATA[langCode]) return;
  localStorage.setItem('cezeri_lang', langCode);
  document.documentElement.lang = langCode.toLowerCase();
  const data = I18N_DATA[langCode];

  // 1. Update text elements having data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (data[key] !== undefined) {
      el.innerHTML = data[key];
    }
  });

  // 2. Update store graphic images dynamically
  const isSubfolder = window.location.pathname.includes('/games/') || window.location.pathname.includes('/blog/') || window.location.pathname.includes('/privacy-policy/') || window.location.pathname.includes('/terms/');
  const basePath = isSubfolder ? '../../assets/images/multimind/store/' : './assets/images/multimind/store/';

  // Update Hero Store Banner
  const heroBanner = document.getElementById('store-hero-banner');
  if (heroBanner) {
    heroBanner.src = basePath + data.storeFolder + '/' + data.banner;
  }

  // Update Games Catalog Image
  const catalogImg = document.getElementById('store-catalog-img');
  if (catalogImg) {
    catalogImg.src = basePath + data.storeFolder + '/' + data.s1;
  }

  // Update Screenshots 1 to 5
  for (let i = 1; i <= 5; i++) {
    const imgEl = document.getElementById('store-screen-' + i);
    if (imgEl) {
      const fileName = data['s' + i];
      imgEl.src = basePath + data.storeFolder + '/' + fileName;
    }
  }

  // 3. Update Language Switcher UI Display
  document.querySelectorAll('.lang-current-label').forEach(el => {
    el.innerHTML = `<span class="text-base">${data.flag}</span> <span class="font-bold text-xs">${data.code}</span>`;
  });

  document.querySelectorAll('.lang-item').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === langCode) {
      btn.classList.add('bg-cyan-500/20', 'text-cyan-300', 'font-bold');
      btn.classList.remove('text-slate-300');
    } else {
      btn.classList.remove('bg-cyan-500/20', 'text-cyan-300', 'font-bold');
      btn.classList.add('text-slate-300');
    }
  });
}

// Initialize on DOM Ready
document.addEventListener('DOMContentLoaded', () => {
  const current = getSavedLanguage();

  // Wire language switcher buttons
  document.querySelectorAll('.lang-item').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const code = btn.getAttribute('data-lang');
      setLanguage(code);
      // Close dropdown if open
      const dropdown = document.getElementById('lang-dropdown');
      if (dropdown) dropdown.classList.add('hidden');
    });
  });

  // Dropdown toggle
  const langTrigger = document.getElementById('lang-trigger');
  const langDropdown = document.getElementById('lang-dropdown');
  if (langTrigger && langDropdown) {
    langTrigger.addEventListener('click', (e) => {
      e.stopPropagation();
      langDropdown.classList.toggle('hidden');
    });

    document.addEventListener('click', () => {
      if (!langDropdown.classList.contains('hidden')) {
        langDropdown.classList.add('hidden');
      }
    });
  }

  // Apply initial language
  setLanguage(current);
});
